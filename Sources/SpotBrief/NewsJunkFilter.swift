import Foundation

/// Отфильтровывает типовой "мусорный" контент, который RSS-ленты новостных
/// сайтов часто подмешивают вперемешку с настоящими новостями: гороскопы,
/// тесты/квизы, регулярные сводки погоды. Это не новости в привычном смысле —
/// у них нет событийного повода, они выходят по расписанию с одним и тем же
/// шаблоном каждый день. Гороскопы вдобавок плохо поддаются суммаризации:
/// на одной странице фактически 12 несвязанных мини-текстов (по знаку
/// зодиака), и экстрактивный суммаризатор, рассчитанный на один связный
/// текст, на таком материале выдавал сборную окрошку из фраз про разные
/// знаки — то самое "битое" краткое содержание.
///
/// Проверяем в основном ЗАГОЛОВОК, а не весь текст — так меньше риск
/// случайно отфильтровать настоящую новость, которая просто упоминает,
/// например, слово "тест" где-то в середине описания.
enum NewsJunkFilter {

    private static let titlePatterns: [String] = [
        // Гороскопы
        "гороскоп", "horoscope", "horoskop",
        // Регулярные сводки погоды (а не новости о погодных катаклизмах —
        // те обычно называются иначе: "ураган", "потоп", "заморозки" и т.п.)
        "прогноз погоды на", "погода на сегодня", "погода на завтра",
        "погода на неделю", "weather forecast for",
        // Тесты/квизы-развлечения
        "тест: ", "квиз: ", "quiz: ", "тест на ", "тест дня"
    ]

    static func isJunk(_ item: NewsItem) -> Bool {
        let title = item.title.lowercased()
        return titlePatterns.contains { title.contains($0) }
    }

    static func filter(_ items: [NewsItem]) -> [NewsItem] {
        items.filter { !isJunk($0) }
    }
}
